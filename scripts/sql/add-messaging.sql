-- =========================================================================
-- Direct messaging between portal accounts, across roles -- any signed-in
-- account can message any other, independent of the Roles & Page Access /
-- Area-scoping system (that governs data pages, not who can DM whom).
--
-- Data model: conversations (1:1 for now) <- conversation_participants
-- (who's in it + their own last_read_at, for unread counts) <- messages.
--
-- Run once, after add-admin-roles-and-areas.sql (profiles must exist).
-- Safe to re-run.
-- =========================================================================

CREATE TABLE IF NOT EXISTS "public"."conversations" (
    "id" bigint NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "last_message_at" timestamp with time zone DEFAULT "now"() NOT NULL
);

ALTER TABLE "public"."conversations" OWNER TO "postgres";

DO $$
BEGIN
  ALTER TABLE "public"."conversations" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
      SEQUENCE NAME "public"."conversations_id_seq"
      START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1
  );
EXCEPTION WHEN duplicate_table THEN
  NULL;
END $$;

ALTER TABLE "public"."conversations" DROP CONSTRAINT IF EXISTS "conversations_pkey";
ALTER TABLE ONLY "public"."conversations" ADD CONSTRAINT "conversations_pkey" PRIMARY KEY ("id");


CREATE TABLE IF NOT EXISTS "public"."conversation_participants" (
    "conversation_id" bigint NOT NULL,
    "profile_id" "uuid" NOT NULL,
    "last_read_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL
);

ALTER TABLE "public"."conversation_participants" OWNER TO "postgres";

ALTER TABLE "public"."conversation_participants" DROP CONSTRAINT IF EXISTS "conversation_participants_pkey";
ALTER TABLE ONLY "public"."conversation_participants"
    ADD CONSTRAINT "conversation_participants_pkey" PRIMARY KEY ("conversation_id", "profile_id");

ALTER TABLE "public"."conversation_participants" DROP CONSTRAINT IF EXISTS "conversation_participants_conversation_id_fkey";
ALTER TABLE ONLY "public"."conversation_participants"
    ADD CONSTRAINT "conversation_participants_conversation_id_fkey" FOREIGN KEY ("conversation_id") REFERENCES "public"."conversations"("id") ON DELETE CASCADE;

