-- =========================================================================
-- Activities: every chapter activity, read from OGD's Activities page or
-- created in Oracle and pushed to OGD.
--
-- One row per activity. OGD activities are keyed by (area_id, ogd_key), where
-- ogd_key is OGD's own id from the activity's link, or its name and start when
-- the link has none. "attendees" holds one object per attendee (member id,
-- name, how they were added); "ogd_details" holds the label/value fields OGD's
-- activity page shows; "ogd_attendee_table" keeps OGD's attendee list as-is.
-- "public_token" is the secret in the activity's attendance link.
--
-- activity_syncs keeps each chapter's last Sync from OGD, with its date range.
--
-- RLS is enabled with NO policies and client roles have no grants, matching
-- ogd_celebrant_reports. Only the /api functions read or write these tables.
--
-- Also registers the "Activities" page for Admin, MSG and Chapter Head.
--
-- Run once, after 2026112201_year_registered_from_id.sql. Safe to re-run.
-- =========================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS "public"."activities" (
    "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "area_id" bigint NOT NULL REFERENCES "public"."areas"("id") ON DELETE CASCADE,
    "source" "text" NOT NULL DEFAULT 'oracle',
    "ogd_key" "text",
    "name" "text" NOT NULL,
    "activity_type" "text",
    "area_name" "text",
    "starts_at" timestamp with time zone,
    "ends_at" timestamp with time zone,
    "team_leader" "text",
    "team_leader_member_id" "text",
    "venue" "text",
    "description" "text",
    "attendance_count" integer,
    "attendees" "jsonb" DEFAULT '[]'::"jsonb" NOT NULL,
    "ogd_details" "jsonb" DEFAULT '{}'::"jsonb" NOT NULL,
    "ogd_attendee_table" "jsonb",
    "ogd_url" "text",
    "public_token" "uuid" DEFAULT "gen_random_uuid"() NOT NULL,
    "push_status" "text",
    "push_failure_code" "text",
    "push_detail" "text",
    "pushed_at" timestamp with time zone,
    "synced_at" timestamp with time zone,
    "created_by" "uuid" REFERENCES "public"."profiles"("id") ON DELETE SET NULL,
    "created_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "updated_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    CONSTRAINT "activities_source_check" CHECK ("source" = ANY (ARRAY['ogd'::"text", 'oracle'::"text"])),
    CONSTRAINT "activities_push_status_check"
      CHECK ("push_status" IS NULL OR "push_status" = ANY (ARRAY['pushing'::"text", 'pushed'::"text", 'failed'::"text"]))
);

CREATE UNIQUE INDEX IF NOT EXISTS "activities_area_ogd_key_idx" ON "public"."activities" ("area_id", "ogd_key");
CREATE UNIQUE INDEX IF NOT EXISTS "activities_public_token_idx" ON "public"."activities" ("public_token");
CREATE INDEX IF NOT EXISTS "activities_starts_at_idx" ON "public"."activities" ("starts_at");

ALTER TABLE "public"."activities" OWNER TO "postgres";
ALTER TABLE "public"."activities" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE "public"."activities" FROM "anon", "authenticated";
GRANT ALL ON TABLE "public"."activities" TO "service_role";

CREATE TABLE IF NOT EXISTS "public"."activity_syncs" (
    "area_id" bigint PRIMARY KEY REFERENCES "public"."areas"("id") ON DELETE CASCADE,
    "date_from" "date",
    "date_to" "date",
    "status" "text" NOT NULL,
    "found" integer DEFAULT 0 NOT NULL,
    "is_partial" boolean DEFAULT false NOT NULL,
    "failure_code" "text",
    "status_detail" "text",
    "synced_at" timestamp with time zone DEFAULT "now"() NOT NULL,
    "synced_by" "uuid" REFERENCES "public"."profiles"("id") ON DELETE SET NULL,
    CONSTRAINT "activity_syncs_status_check" CHECK ("status" = ANY (ARRAY['synced'::"text", 'failed'::"text"]))
);

ALTER TABLE "public"."activity_syncs" OWNER TO "postgres";
ALTER TABLE "public"."activity_syncs" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE "public"."activity_syncs" FROM "anon", "authenticated";
GRANT ALL ON TABLE "public"."activity_syncs" TO "service_role";


-- ---------- Page registration ----------
INSERT INTO "public"."pages" ("key", "label", "sort_order") VALUES
    ('activities', 'Activities', 24)
ON CONFLICT ("key") DO NOTHING;

INSERT INTO "public"."role_pages" ("role_id", "page_key")
SELECT "id", 'activities' FROM "public"."roles" WHERE "name" IN ('Admin', 'MSG', 'Chapter Head')
ON CONFLICT DO NOTHING;

